function venture(
  id,
  name,
  description,
  baseCost,
  baseYield,
  seconds,
  manager,
  managerPokemonId,
  managerCost,
  color,
  upgradeName,
  shop,
) {
  return {
    id,
    name,
    description,
    baseCost,
    baseYield,
    seconds,
    manager,
    managerPokemonId,
    managerCost,
    color,
    icon: `item-${shop.good}`,
    upgradeName,
    district:
      baseCost < 1000 ? "street" : baseCost <= 1000000 ? "city" : "global",
    shop,
  };
}
function storefront(sign, good, product, preferred, loved, neutral, accent) {
  return { sign, good, product, preferred, loved, neutral, accent };
}
